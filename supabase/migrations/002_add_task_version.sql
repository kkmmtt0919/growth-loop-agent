-- =============================================================
-- 002：tasks 增加 version 列
-- 目的：任务每次状态切换 version+1，账本入账 key 带版本号
--   （task:{id}:xp:v{n}），使"完成→撤销→再完成"各步入账 key 唯一，
--   不会因首次完成占用的 key 冲突而跳过后续入账。
-- =============================================================

alter table public.tasks
  add column version int not null default 0;
